// Service Worker — Instructivo de Viáticos MVCS
// Habilita instalación (Android/Chrome) y uso sin conexión de la página principal.
const CACHE_NAME = 'viaticos-mvcs-v1';
const CORE_ASSETS = [
  './INSTRUCTIVO_DE_VIATICOS_2026.html',
  './manifest.json',
  './icon-192.png',
  './icon-512.png',
  './icon-512-maskable.png',
  './apple-touch-icon.png'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(CORE_ASSETS))
      .catch(() => {}) // no bloquear la instalación si algún asset falla
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

// Estrategia: stale-while-revalidate para GET del mismo origen.
// Deja pasar directo las peticiones cross-origin (fuentes, pdf.js, PDF externo).
self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  const sameOrigin = url.origin === self.location.origin;
  if (!sameOrigin) return; // deja que el navegador maneje CDNs / recursos externos

  event.respondWith(
    caches.open(CACHE_NAME).then(async (cache) => {
      const cached = await cache.match(req);
      const network = fetch(req)
        .then((res) => {
          if (res && res.status === 200) cache.put(req, res.clone());
          return res;
        })
        .catch(() => cached);
      return cached || network;
    })
  );
});
